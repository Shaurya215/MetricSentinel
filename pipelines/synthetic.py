"""Generate a small, FAKE dataset with the same files and columns as Olist.

This exists only so the pipeline can be tested and smoke-run without the real
dataset. Nothing produced here may be used for results, EDA findings or evaluation.
The output folder contains a `SYNTHETIC_DATA.txt` marker.

Besides ordinary random orders, it plants fixed edge cases (named in `EDGE`) that
mirror the data issues listed in DATA_PLAN.md section 3, so tests can assert on them.

    uv run --group data python -m pipelines.synthetic --out data/synthetic
"""

from __future__ import annotations

import argparse
import csv
import random
from datetime import datetime, timedelta
from pathlib import Path

STATES = ["SP", "RJ", "MG", "RS", "PR", "BA", "SC", "PE"]
CATEGORIES_PT = [
    "beleza_saude",
    "informatica_acessorios",
    "cama_mesa_banho",
    "esporte_lazer",
    "moveis_decoracao",
    "brinquedos",
    "pc_gamer",  # deliberately absent from the translation file (real Olist has this gap)
]
CATEGORIES_EN = {
    "beleza_saude": "health_beauty",
    "informatica_acessorios": "computers_accessories",
    "cama_mesa_banho": "bed_bath_table",
    "esporte_lazer": "sports_leisure",
    "moveis_decoracao": "furniture_decor",
    "brinquedos": "toys",
}
PAYMENT_TYPES = ["credit_card", "credit_card", "credit_card", "boleto", "voucher", "debit_card"]

# Fixed ids for planted edge cases (all purchased on EDGE_DAY).
EDGE_DAY = datetime(2017, 6, 15, 10, 0, 0)
EDGE = {
    "no_items": "edge_order_no_items",
    "no_payment": "edge_order_no_payment",
    "delivered_no_date": "edge_order_delivered_missing_date",
    "dup_review": "edge_order_two_reviews",
    "shared_review_a": "edge_order_shared_review_a",
    "shared_review_b": "edge_order_shared_review_b",
    "unknown_category": "edge_order_unknown_category",
    "null_category": "edge_order_null_category",
    "split_payment": "edge_order_split_payment",
    "not_defined_payment": "edge_order_not_defined_payment",
    "late": "edge_order_late",
    "on_time": "edge_order_on_time",
    "multiline_review": "edge_order_multiline_review",
}
EDGE_REPEAT_CUSTOMER_UNIQUE_ID = "unique_edge_repeat"

FMT = "%Y-%m-%d %H:%M:%S"


def _ts(value: datetime | None) -> str:
    return "" if value is None else value.strftime(FMT)


def _write(path: Path, header: list[str], rows: list[list[object]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)


def generate(
    out_dir: Path,
    *,
    n_orders: int = 2500,
    seed: int = 7,
    start: str = "2017-01-01",
    end: str = "2018-08-31",
    n_sellers: int = 40,
    n_products: int = 120,
) -> dict[str, int]:
    """Write the nine CSV files into `out_dir` and return the row count per file."""
    rng = random.Random(seed)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "SYNTHETIC_DATA.txt").write_text(
        "FAKE data generated by pipelines/synthetic.py. Not Olist. Never use for results.\n",
        encoding="utf-8",
    )

    first, last = datetime.fromisoformat(start), datetime.fromisoformat(end)
    span_days = (last - first).days

    sellers: list[list[object]] = [
        [f"seller_{i:03d}", f"{10000 + i}", f"city_{i % 9}", STATES[i % len(STATES)]]
        for i in range(n_sellers)
    ]
    products = []
    for i in range(n_products):
        cat = CATEGORIES_PT[i % len(CATEGORIES_PT)] if i % 25 else ""  # a few null categories
        products.append(
            [f"prod_{i:04d}", cat, 40 + i % 30, 300 + i, 1 + i % 5, 200 + 10 * i, 20, 10, 15]
        )
    n_customers = max(n_orders // 5 * 4, 10)
    unique_ids = [f"unique_{i:05d}" for i in range(n_customers)]

    orders: list[list[object]] = []
    items: list[list[object]] = []
    payments: list[list[object]] = []
    reviews: list[list[object]] = []
    customers: list[list[object]] = []

    def add_customer(order_id: str, unique_id: str, state: str) -> str:
        customer_id = f"cust_{order_id}"
        customers.append(
            [customer_id, unique_id, f"{20000 + len(customers) % 500}", "somecity", state]
        )
        return customer_id

    def add_order(
        order_id: str,
        purchase: datetime,
        *,
        status: str = "delivered",
        unique_id: str | None = None,
        state: str | None = None,
        delivered: datetime | str | None = "auto",
        late: bool = False,
    ) -> None:
        unique_id = unique_id or rng.choice(unique_ids)
        state = state or rng.choice(STATES)
        customer_id = add_customer(order_id, unique_id, state)
        approved = purchase + timedelta(hours=rng.randint(1, 20))
        carrier = approved + timedelta(days=rng.randint(1, 3))
        estimated = (purchase + timedelta(days=rng.randint(14, 25))).replace(
            hour=0, minute=0, second=0
        )
        if delivered == "auto":
            if status != "delivered":
                delivered_ts = None
            elif late:
                delivered_ts = estimated + timedelta(days=rng.randint(2, 8), hours=5)
            else:
                delivered_ts = purchase + timedelta(
                    days=rng.randint(4, 12), hours=rng.randint(0, 20)
                )
        else:
            delivered_ts = delivered  # type: ignore[assignment]
        orders.append(
            [
                order_id,
                customer_id,
                status,
                _ts(purchase),
                _ts(approved) if status != "created" else "",
                _ts(carrier) if status in ("shipped", "delivered") else "",
                _ts(delivered_ts),  # type: ignore[arg-type]
                _ts(estimated),
            ]
        )

    def add_items(
        order_id: str,
        n: int,
        seller: str | None = None,
        product: str | None = None,
        purchase: datetime | None = None,
    ) -> float:
        total = 0.0
        for seq in range(1, n + 1):
            prod = product or rng.choice(products)[0]
            sel = seller or rng.choice(sellers)[0]
            price = round(rng.uniform(15, 350), 2)
            freight = round(rng.uniform(5, 40), 2)
            total += price + freight
            ship = (purchase or EDGE_DAY) + timedelta(days=3)
            items.append([order_id, seq, prod, sel, _ts(ship), price, freight])
        return total

    def add_payment(
        order_id: str, seq: int, kind: str, value: float, installments: int = 1
    ) -> None:
        payments.append([order_id, seq, kind, installments, round(value, 2)])

    def add_review(
        review_id: str,
        order_id: str,
        score: int,
        created: datetime,
        comment: str = "",
        title: str = "",
        answered_after_h: int = 24,
    ) -> None:
        reviews.append(
            [
                review_id,
                order_id,
                score,
                title,
                comment,
                _ts(created.replace(hour=0, minute=0, second=0)),
                _ts(created + timedelta(hours=answered_after_h)),
            ]
        )

    # ---- ordinary orders, volume ramps up like the real data ----
    for n in range(n_orders):
        # square-root skew toward later dates -> sparse start, dense middle
        day = int(span_days * (rng.random() ** 0.7))
        purchase = first + timedelta(days=day, hours=rng.randint(0, 23), minutes=rng.randint(0, 59))
        order_id = f"order_{n:06d}"
        status = rng.choices(["delivered", "canceled", "shipped", "unavailable"], [90, 4, 4, 2])[0]
        add_order(order_id, purchase, status=status, late=rng.random() < 0.08)
        total = add_items(order_id, rng.choices([1, 2, 3], [80, 15, 5])[0], purchase=purchase)
        add_payment(order_id, 1, rng.choice(PAYMENT_TYPES), total, rng.choice([1, 1, 2, 3, 6, 10]))
        if status == "delivered" and rng.random() < 0.9:
            created = purchase + timedelta(days=rng.randint(8, 20))
            add_review(
                f"review_{n:06d}",
                order_id,
                rng.choices([1, 2, 3, 4, 5], [8, 4, 10, 25, 53])[0],
                created,
                comment=rng.choice(["", "", "Chegou rapido, recomendo", "Produto ok"]),
            )

    # ---- planted edge cases (DATA_PLAN.md section 3) ----
    d = EDGE_DAY
    add_order(EDGE["no_items"], d)  # order with no items
    add_payment(EDGE["no_items"], 1, "credit_card", 50.0)

    add_order(EDGE["no_payment"], d)  # order with no payment
    add_items(EDGE["no_payment"], 1, purchase=d)

    add_order(
        EDGE["delivered_no_date"], d, status="delivered", delivered=None
    )  # delivered, no date
    total = add_items(EDGE["delivered_no_date"], 1, purchase=d)
    add_payment(EDGE["delivered_no_date"], 1, "credit_card", total)

    add_order(EDGE["dup_review"], d)  # two reviews for one order; the later answer must win
    total = add_items(EDGE["dup_review"], 1, purchase=d)
    add_payment(EDGE["dup_review"], 1, "credit_card", total)
    add_review(
        "review_dup_old", EDGE["dup_review"], 1, d + timedelta(days=10), "ruim", answered_after_h=5
    )
    add_review(
        "review_dup_new",
        EDGE["dup_review"],
        5,
        d + timedelta(days=11),
        "mudei de ideia",
        answered_after_h=48,
    )

    for key in ("shared_review_a", "shared_review_b"):  # one review_id reused across two orders
        add_order(EDGE[key], d)
        total = add_items(EDGE[key], 1, purchase=d)
        add_payment(EDGE[key], 1, "credit_card", total)
    add_review("review_shared", EDGE["shared_review_a"], 4, d + timedelta(days=9), "bom")
    add_review("review_shared", EDGE["shared_review_b"], 4, d + timedelta(days=9), "bom")

    add_order(EDGE["unknown_category"], d)  # category with no English translation
    total = add_items(
        EDGE["unknown_category"], 1, product="prod_0006", purchase=d
    )  # a pc_gamer product
    add_payment(EDGE["unknown_category"], 1, "boleto", total)

    add_order(EDGE["null_category"], d)  # product with a null category
    total = add_items(EDGE["null_category"], 1, product="prod_0000", purchase=d)
    add_payment(EDGE["null_category"], 1, "boleto", total)

    add_order(EDGE["split_payment"], d)  # voucher first, bigger card payment second
    total = add_items(EDGE["split_payment"], 1, purchase=d)
    add_payment(EDGE["split_payment"], 1, "voucher", 10.0)
    add_payment(EDGE["split_payment"], 2, "credit_card", max(total - 10.0, 1.0))

    add_order(EDGE["not_defined_payment"], d)
    total = add_items(EDGE["not_defined_payment"], 1, purchase=d)
    add_payment(EDGE["not_defined_payment"], 1, "not_defined", total)

    estimated = datetime(2017, 6, 25)  # fixed so the late/on-time flags are exact
    for key, delivered in (
        ("late", datetime(2017, 6, 28, 9)),
        ("on_time", datetime(2017, 6, 25, 23, 30)),
    ):
        order_id = EDGE[key]
        customer_id = add_customer(order_id, rng.choice(unique_ids), "SP")
        orders.append(
            [
                order_id,
                customer_id,
                "delivered",
                _ts(d),
                _ts(d + timedelta(hours=2)),
                _ts(d + timedelta(days=2)),
                _ts(delivered),
                _ts(estimated),
            ]
        )
        total = add_items(order_id, 1, purchase=d)
        add_payment(order_id, 1, "credit_card", total)

    add_order(EDGE["multiline_review"], d)  # quotes, commas and a newline inside one CSV field
    total = add_items(EDGE["multiline_review"], 1, purchase=d)
    add_payment(EDGE["multiline_review"], 1, "credit_card", total)
    add_review(
        "review_multiline",
        EDGE["multiline_review"],
        2,
        d + timedelta(days=9),
        'Linha um, "entre aspas"\nlinha dois',
        title="Atraso",
    )

    # a person who orders twice, from two different states (customer_id differs per order)
    for k, state in enumerate(("SP", "RJ")):
        oid = f"edge_repeat_{k}"
        add_order(
            oid, d + timedelta(days=30 * k), unique_id=EDGE_REPEAT_CUSTOMER_UNIQUE_ID, state=state
        )
        total = add_items(oid, 1, purchase=d)
        add_payment(oid, 1, "credit_card", total)

    geolocation = [
        [10000 + i, -23.5 - i / 100, -46.6 - i / 100, "somecity", STATES[i % len(STATES)]]
        for i in range(60)
    ]
    translation: list[list[object]] = [[pt, en] for pt, en in CATEGORIES_EN.items()]

    spec: dict[str, tuple[list[str], list[list[object]]]] = {
        "olist_orders_dataset.csv": (
            [
                "order_id",
                "customer_id",
                "order_status",
                "order_purchase_timestamp",
                "order_approved_at",
                "order_delivered_carrier_date",
                "order_delivered_customer_date",
                "order_estimated_delivery_date",
            ],
            orders,
        ),
        "olist_order_items_dataset.csv": (
            [
                "order_id",
                "order_item_id",
                "product_id",
                "seller_id",
                "shipping_limit_date",
                "price",
                "freight_value",
            ],
            items,
        ),
        "olist_order_payments_dataset.csv": (
            [
                "order_id",
                "payment_sequential",
                "payment_type",
                "payment_installments",
                "payment_value",
            ],
            payments,
        ),
        "olist_order_reviews_dataset.csv": (
            [
                "review_id",
                "order_id",
                "review_score",
                "review_comment_title",
                "review_comment_message",
                "review_creation_date",
                "review_answer_timestamp",
            ],
            reviews,
        ),
        "olist_customers_dataset.csv": (
            [
                "customer_id",
                "customer_unique_id",
                "customer_zip_code_prefix",
                "customer_city",
                "customer_state",
            ],
            customers,
        ),
        "olist_sellers_dataset.csv": (
            ["seller_id", "seller_zip_code_prefix", "seller_city", "seller_state"],
            sellers,
        ),
        "olist_products_dataset.csv": (
            [
                "product_id",
                "product_category_name",
                "product_name_lenght",
                "product_description_lenght",
                "product_photos_qty",
                "product_weight_g",
                "product_length_cm",
                "product_height_cm",
                "product_width_cm",
            ],
            products,
        ),
        "olist_geolocation_dataset.csv": (
            [
                "geolocation_zip_code_prefix",
                "geolocation_lat",
                "geolocation_lng",
                "geolocation_city",
                "geolocation_state",
            ],
            geolocation,
        ),
        "product_category_name_translation.csv": (
            ["product_category_name", "product_category_name_english"],
            translation,
        ),
    }
    counts = {}
    for filename, (header, rows) in spec.items():
        _write(out_dir / filename, header, rows)
        counts[filename] = len(rows)
    return counts


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate FAKE Olist-shaped data for tests.")
    parser.add_argument("--out", type=Path, default=Path("data/synthetic"))
    parser.add_argument("--orders", type=int, default=2500)
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args()
    counts = generate(args.out, n_orders=args.orders, seed=args.seed)
    print(f"Wrote FAKE data to {args.out}: {counts}")


if __name__ == "__main__":
    main()
