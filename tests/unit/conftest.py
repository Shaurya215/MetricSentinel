@pytest.fixture
def mutate_csv() -> Callable[[Path, str, Callable[[list[list[str]]], None]], None]:
    """Rewrite one CSV through a function that edits its rows (header is rows[0])."""

    def _mutate(raw_dir: Path, filename: str, edit: Callable[[list[list[str]]], None]) -> None:
        path = raw_dir / filename
        with path.open(newline="", encoding="utf-8") as handle:
            rows = list(csv.reader(handle))
        edit(rows)
        with path.open("w", newline="", encoding="utf-8") as handle:
            csv.writer(handle, lineterminator="\n").writerows(rows)
        (raw_dir / "checksums.json").unlink(missing_ok=True)  # the file changed on purpose

    return _mutate


@pytest.fixture
def copy_dataset(small_raw: Path, tmp_path: Path) -> Callable[[], Path]:
    def _copy() -> Path:
        target = tmp_path / f"copy_{len(list(tmp_path.glob('copy_*')))}"
        shutil.copytree(small_raw, target)
        return target

    return _copy


